#!/usr/bin/env node
/**
 * Security Suite S1 — generate the transaction allow-list from the reviewed
 * deployment record.
 *
 *   node scripts/security/gen-tx-allowlist.mjs            # write the file
 *   node scripts/security/gen-tx-allowlist.mjs --check    # exit 1 on drift
 *
 * Reads deployments/preprod-v1.json and writes src/lib/tx-allowlist.generated.ts:
 * every confirmed script hash, policy, address and reward address the app may
 * ever put in a transaction. Never hand-edit the output; a test fails on drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SOURCE = "deployments/preprod-v1.json";
const OUT = "src/lib/tx-allowlist.generated.ts";

export function buildAllowList(record) {
  const scripts = new Map();
  const addresses = new Map();
  const rewardAddresses = new Map();
  const policies = new Map();
  const hex56 = /^[0-9a-f]{56}$/;

  const visit = (node, path, inheritedStatus) => {
    if (!node || typeof node !== "object" || Array.isArray(node)) return;
    const status = typeof node.status === "string" ? node.status : inheritedStatus;
    const role = path.join(".");
    if (status === "confirmed") {
      if (typeof node.scriptHash === "string" && hex56.test(node.scriptHash)) {
        if (!scripts.has(node.scriptHash)) scripts.set(node.scriptHash, role);
      }
      for (const key of ["address", "lockAddress", "treasuryAddress"]) {
        const a = node[key];
        if (typeof a === "string" && a.startsWith("addr_test1") && !addresses.has(a)) {
          addresses.set(a, `${role}.${key}`);
        }
      }
      if (typeof node.rewardAddress === "string" && node.rewardAddress.startsWith("stake_test1")) {
        rewardAddresses.set(node.rewardAddress, role);
      }
      for (const key of ["tsraPolicyId", "stsraPolicyId", "policyId"]) {
        const p = node[key];
        if (typeof p === "string" && hex56.test(p) && !policies.has(p))
          policies.set(p, `${role}.${key}`);
      }
    }
    for (const [k, v] of Object.entries(node)) {
      if (k === "params" || k === "bounds") continue;
      visit(v, [...path, k], status);
    }
  };
  visit(record, [], undefined);

  const sorted = (m) => [...m.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1));
  return {
    label: String(record.label),
    network: String(record.network),
    scripts: sorted(scripts),
    policies: sorted(policies),
    addresses: sorted(addresses),
    rewardAddresses: sorted(rewardAddresses),
  };
}

export function renderAllowList(list) {
  const rows = (entries) =>
    entries
      .map(
        ([value, role]) =>
          `    { value: ${JSON.stringify(value)}, role: ${JSON.stringify(role)} },`,
      )
      .join("\n");
  return `/**
 * GENERATED by scripts/security/gen-tx-allowlist.mjs from ${SOURCE}.
 * Do not edit by hand: change the deployment record and regenerate.
 * A test fails if this file drifts from its source.
 */

export interface AllowEntry {
  readonly value: string;
  readonly role: string;
}

export const DEPLOYED_ALLOWLIST = {
  label: ${JSON.stringify(list.label)},
  network: ${JSON.stringify(list.network)},
  scripts: [
${rows(list.scripts)}
  ] as readonly AllowEntry[],
  policies: [
${rows(list.policies)}
  ] as readonly AllowEntry[],
  addresses: [
${rows(list.addresses)}
  ] as readonly AllowEntry[],
  rewardAddresses: [
${rows(list.rewardAddresses)}
  ] as readonly AllowEntry[],
} as const;
`;
}

/** The generated file's exact text, formatted with the repo's Prettier config. */
export async function generate() {
  const record = JSON.parse(readFileSync(join(root, SOURCE), "utf8"));
  const target = join(root, OUT);
  const raw = renderAllowList(buildAllowList(record));
  try {
    const prettier = await import("prettier");
    const config = (await prettier.resolveConfig(target)) ?? {};
    return await prettier.format(raw, { ...config, filepath: target });
  } catch {
    return raw; // Prettier not installed: content is identical, layout may differ.
  }
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const text = await generate();
  const target = join(root, OUT);
  if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8");
    if (current !== text) {
      console.error(`${OUT} is out of date; run node scripts/security/gen-tx-allowlist.mjs`);
      process.exit(1);
    }
    console.log(`${OUT} matches ${SOURCE}`);
  } else {
    writeFileSync(target, text);
    console.log(`wrote ${OUT}`);
  }
}
