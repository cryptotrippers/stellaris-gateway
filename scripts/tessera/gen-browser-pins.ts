/**
 * Writes src/lib/tessera-queue-script.generated.ts: the APPLIED `redeem_queue`
 * script of a Tessera deployment, for the browser builders.
 *
 * Every other Tessera script the browser needs is read from an on-chain
 * reference script, but `redeem_queue` has none, and the 546 kB blueprint is
 * too big for the client bundle. The applied script is 3.1 kB. The browser
 * checks its hash against the deployment before use, and
 * tests/contracts/tessera-browser.test.ts re-derives it from the pinned
 * blueprint and the recorded seed, so it cannot drift silently.
 *
 *   npx tsx scripts/tessera/gen-browser-pins.ts [--label preprod-v1]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { applyQueueScripts, applyRedeemQueue, applyReserve } from "./lib/blueprint";

const i = process.argv.indexOf("--label");
const LABEL = i > 0 ? process.argv[i + 1]! : "preprod-v1";
const dep = JSON.parse(readFileSync(`deployments/${LABEL}.json`, "utf8")) as {
  reserve: { seed: { txHash: string; outputIndex: number }; scriptHash: string };
  queue: { seed: { txHash: string; outputIndex: number }; scriptHash: string };
};

export function appliedQueueScript(d: typeof dep): string {
  const reserve = applyReserve(d.reserve.seed);
  if (reserve.hash !== d.reserve.scriptHash) throw new Error("reserve hash drift");
  const qs = applyQueueScripts(reserve.hash);
  const queue = applyRedeemQueue(d.queue.seed, reserve.hash, {
    flow: qs.flow.hash,
    admin: qs.admin.hash,
    short: qs.short.hash,
  });
  if (queue.hash !== d.queue.scriptHash) throw new Error("queue hash drift");
  return queue.script.script;
}

if (process.argv[1]?.endsWith("gen-browser-pins.ts")) {
  const cbor = appliedQueueScript(dep);
  const out = `/**
 * GENERATED by scripts/tessera/gen-browser-pins.ts from deployments/${LABEL}.json
 * and contracts/tessera/plutus.json — do not edit. The applied \`redeem_queue\`
 * script (${cbor.length / 2} bytes); its hash is checked before every use and
 * re-derived in tests/contracts/tessera-browser.test.ts.
 */
export const TESSERA_QUEUE_SCRIPT_${LABEL.replace(/[^a-z0-9]/gi, "_").toUpperCase()} =
  "${cbor}";
`;
  writeFileSync("src/lib/tessera-queue-script.generated.ts", out);
  console.log(`wrote src/lib/tessera-queue-script.generated.ts (${cbor.length / 2} bytes)`);
}
